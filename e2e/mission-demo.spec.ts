import { expect, test } from '@playwright/test'

test('guided mission executes seven real steps and preserves review boundaries', async ({ page, request }) => {
  await page.goto('/app')
  await expect(page.getByTestId('backend-mode')).toHaveText('NestJS conectado')
  await page.getByTestId('start-mission-demo').click()
  const guide = page.getByTestId('mission-demo-controller')
  await expect(guide).toContainText('1/7')
  await expect(page.getByTestId('mission-demo-evidence')).toContainText('70 / 64')
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('2/7')
  await expect(page.getByTestId('mission-demo-evidence')).toContainText('104 / 64')
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('3/7')
  await expect(page).toHaveURL(/alertas/)
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('4/7')
  await expect(page.getByRole('dialog', { name: /Quirón/ })).toBeVisible()
  await page.getByRole('button', { name: /Close Quirón chat|Cerrar chat de Quirón/ }).click()
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('5/7')
  await expect(page).toHaveURL(/medico/)
  const sid = await page.evaluate(() => sessionStorage.getItem('vitalink-simulation-id'))
  const snapshot = async () => (await (await request.get('/api/simulation', { headers: { 'X-Simulation-Id': sid! } })).json()).state
  expect((await snapshot()).communications.filter((c: { status: string }) => c.status === 'queued')).toHaveLength(1)
  const queued = await snapshot()
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('6/7')
  let state = await snapshot()
  expect(state.link).toBe('down')
  expect(state.communications[0].status).toBe('queued')
  await page.getByTestId('mission-demo-next').click()
  await expect(guide).toContainText('7/7')
  state = await snapshot()
  expect(state.audit.slice(0, queued.audit.length)).toEqual(queued.audit)
  expect(state.communications[0].id).toBe(queued.communications[0].id)
  expect(state.link).toBe('up')
  expect(state.communications).toHaveLength(1)
  expect(state.communications[0].status).toBe('received')
  expect(state.episodes.some((e: { status: string }) => e.status !== 'closed')).toBe(true)
  await page.screenshot({ path: 'artifacts/mission-demo-step7.png' })
  await page.getByTestId('mission-demo-step-5').click()
  await expect(guide).toContainText('5/7')
  expect((await snapshot()).communications).toHaveLength(1)
})

test('guided demonstration also runs with the API unavailable', async ({ page }) => {
  await page.route((url) => url.pathname.startsWith('/api/'), (route) => route.abort())
  await page.goto('/app')
  await expect(page.getByTestId('backend-mode')).toHaveText('Simulador local')
  await page.getByTestId('start-mission-demo').click()
  await expect(page.getByTestId('mission-demo-controller')).toContainText('1/7')
  await page.getByTestId('mission-demo-step-7').click()
  await expect(page.getByTestId('mission-demo-controller')).toContainText('7/7')
  await expect(page.getByTestId('mission-demo-evidence')).toContainText('Local simulator')
})
